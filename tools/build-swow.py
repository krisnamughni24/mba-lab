#!/usr/bin/env python3
"""Build simulations/word-network/data/swow.js from the Small World of Words English norms (SWOW-EN, R123 strength file).

Usage: python3 tools/build-swow.py path/to/strength.SWOW-EN.R123.20180827.csv [top_n]

Source: De Deyne, Navarro, Perfors, Brysbaert & Storms (2019), "The Small World of Words English word association norms for
over 12,000 cue words", Behavior Research Methods. https://smallworldofwords.org  Licence CC BY-NC-ND 3.0 (see docs/DATA-SOURCES.md).
Output keeps, per cue, its strongest responses that are themselves cues (so every node can be expanded). Weights are stored as
integers (strength x 1000).
"""
import sys, json, collections

src = sys.argv[1]
top = int(sys.argv[2]) if len(sys.argv) > 2 else 10
edges = collections.defaultdict(list)
with open(src, encoding='utf8') as f:
    f.readline()
    for line in f:
        p = line.rstrip('\n').split('\t')
        if len(p) == 5:
            edges[p[0]].append((p[1], float(p[4])))
cues = sorted(edges)
cue_set = set(cues)
idx = {w: i for i, w in enumerate(cues)}
rows, n = [], 0
for w in cues:
    keep = [(r, s) for r, s in sorted(edges[w], key=lambda x: -x[1]) if r in cue_set and r != w and s >= 0.004][:top]
    flat = []
    for r, s in keep:
        flat += [idx[r], max(1, round(s * 1000))]
    rows.append(flat)
    n += len(keep)
out = 'simulations/word-network/data/swow.js'
with open(out, 'w', encoding='utf8') as f:
    f.write('/* GENERATED by tools/build-swow.py - do not edit. Small World of Words (SWOW-EN, 2018), CC BY-NC-ND 3.0, https://smallworldofwords.org */\n')
    f.write('window.MBALAB = window.MBALAB || {}; MBALAB.wordnet = MBALAB.wordnet || {};\n')
    f.write('MBALAB.wordnet.raw = {w:' + json.dumps(cues, ensure_ascii=False, separators=(',', ':')) + ',e:' + json.dumps(rows, separators=(',', ':')) + '};\n')
print('words', len(cues), 'edges', n, 'bytes', len(open(out, encoding='utf8').read()))
